.reference ___dtrace_typedefs\$stab\$v2
.subsections_via_symbols
EOF
$CC -o $t/a.o -c $t/a.s
$CC --ld-path=$mold -o $t/exe $t/a.o
dof_dump -x $t/exe > $t/dof
